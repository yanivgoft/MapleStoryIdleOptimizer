#!/usr/bin/env python3
"""Golden test: ``engine.classes.buccaneer.compute`` against the frozen numbers of the ORIGINAL Buccaneer verify script
(tests/golden/buccaneer_golden.json, regenerated by make_golden_buccaneer.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_buccaneer.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_buccaneer.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import buccaneer  # noqa: E402
import golden_harness as GH  # noqa: E402

GOLDEN = HERE / "buccaneer_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("hook_bomber_dps", out["hook_bomber_dps"], rows["HOOK_BOMBER"]["dps"])
    chk("sea_serpent_burst_dps", out["sea_serpent_burst_dps"], rows["SEA_SERPENT_BURST"]["dps"])
    chk("serpent_assault_dps", out["serpent_assault_dps"], rows["SERPENT_ASSAULT"]["dps"])
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    for k, pair in out["branch_pairs"].items():       # every Buccaneer row has an explicit per-branch pair = the row's boss / normal DPS
        chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "cast_rate_avg", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active",
              "as_bonus", "crit_damage_bonus", "final_damage_extra", "final_damage_rest", "monster_dmg_bonus", "maple_hero_pct",
              "serpent_scale_avg", "crossbones_full", "time_leap_full", "speed_infusion_full", "roll_of_dice_pct"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.basic_attacks_per_second", out["hook_bomber_per_second"], d["basic_attacks_per_second"])
    chk("derived.basic_attacks_per_second_avg", out["hook_bomber_per_second_avg"], d["basic_attacks_per_second_avg"])
    chk("derived.attack_bucket_mult", out["attack_bucket_mult"], d["attack_bucket_mult"])
    chk("derived.assault_mode_uptime", out["uptime"], d["assault_mode_uptime"])
    chk("derived.serpent_interval_s", out["serpent_T"], d["serpent_interval_s"])
    chk("derived.octopunch_cooldown", out["OCTOPUNCH_COOLDOWN"], d["octopunch_cooldown"])
    GH.check_stunned_shares(chk, out, d)
    GH.check_engine_and_companion(chk, out, res)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(buccaneer, GOLDEN, compare, rtol, verbose)


def test_buccaneer_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
