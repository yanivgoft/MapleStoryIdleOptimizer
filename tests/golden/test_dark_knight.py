#!/usr/bin/env python3
"""Golden test: ``engine.classes.dark_knight.compute`` against the frozen numbers of the ORIGINAL Dark Knight verify script
(tests/golden/dark_knight_golden.json, regenerated by make_golden_dark_knight.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_dark_knight.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_dark_knight.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import dark_knight  # noqa: E402
import golden_harness as GH  # noqa: E402

FACTOR_MODE = GH.FACTOR_MODE        # legacy 300-clamp (workbook golden)

GOLDEN = HERE / "dark_knight_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("dark_impale_dps", out["dark_impale_dps"], rows["DARK_IMPALE"]["dps"])
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    for k, pair in out["branch_pairs"].items():       # every Dark Knight row has an explicit per-branch pair = the row's boss / normal DPS
        chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active", "attack_bucket_sum",
              "as_bonus", "crit_rate_bonus", "crit_damage_bonus", "final_damage_extra", "monster_dmg_bonus", "maple_hero_pct",
              "total_defense", "iron_wall_str_bonus", "final_attack_pct", "advanced_final_attack_pct", "evil_eye_shock_enh_pct", "hex_avg",
              "hex_boss_avg", "dark_resonance_avg", "dark_resonance_boss_avg", "cross_over_chains_avg", "hyper_body_avg", "evil_eye_avg",
              "magic_crash_weaken_avg", "lord_critrate_avg", "lord_critdmg_avg"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.basic_attacks_per_second", out["dark_impale_per_second"], d["basic_attacks_per_second"])
    chk("derived.attack_bucket_mult", out["attack_bucket_mult"], d["attack_bucket_mult"])
    GH.check_stunned_shares(chk, out, d)
    GH.check_engine_and_companion(chk, out, res, companion_present=True)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(dark_knight, GOLDEN, compare, rtol, verbose)


def test_dark_knight_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
