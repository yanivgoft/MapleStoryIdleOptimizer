#!/usr/bin/env python3
"""Golden test: ``engine.classes.paladin.compute`` against the frozen numbers of the ORIGINAL Paladin verify script
(tests/golden/paladin_golden.json, regenerated by make_golden_paladin.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_paladin.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_paladin.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import paladin  # noqa: E402
import golden_harness as GH  # noqa: E402

FACTOR_MODE = GH.FACTOR_MODE        # legacy 300-clamp (workbook golden)

GOLDEN = HERE / "paladin_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("blast_dps", out["blast_dps"], rows["BLAST"]["dps"])
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    for k, pair in out["branch_pairs"].items():       # every Paladin row has an explicit per-branch pair = the row's boss / normal DPS
        chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "cast_rate_avg", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active", "attack_bucket_sum",
              "as_bonus", "crit_damage_bonus", "final_damage_extra", "monster_dmg_bonus", "maple_hero_pct"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.basic_attacks_per_second", out["blast_per_second"], d["basic_attacks_per_second"])
    chk("derived.basic_attacks_per_second_avg", out["blast_per_second_avg"], d["basic_attacks_per_second_avg"])
    chk("derived.attack_bucket_mult", out["attack_bucket_mult"], d["attack_bucket_mult"])
    chk("derived.combat_orders_uptime", out["co_u"], d["combat_orders_uptime"])
    chk("derived.combat_orders_skill_level_bonus", out["co_f"], d["combat_orders_skill_level_bonus"])
    chk("derived.vessel_of_light_uptime", out["vessel_of_light_uptime"], d["vessel_of_light_uptime"])
    GH.check_stunned_shares(chk, out, d)
    GH.check_engine_and_companion(chk, out, res)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(paladin, GOLDEN, compare, rtol, verbose)


def test_paladin_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
