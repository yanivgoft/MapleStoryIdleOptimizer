#!/usr/bin/env python3
"""Golden test: ``engine.classes.marksman.compute`` against the frozen numbers of the ORIGINAL Marksman verify script
(tests/golden/marksman_golden.json, regenerated by make_golden_marksman.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_marksman.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_marksman.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import marksman  # noqa: E402
import golden_harness as GH  # noqa: E402

GOLDEN = HERE / "marksman_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("epa_dps", out["epa_dps"], rows["EMPOWERED_PIERCING_ARROW"]["dps"])
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    for k, pair in out["branch_pairs"].items():       # every Marksman row has an explicit per-branch pair = the row's boss / normal DPS
        chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active", "attack_bucket_sum",
              "as_bonus", "crit_damage_bonus", "crit_rate_bonus", "mortal_blow_bonus", "monster_dmg_bonus", "maple_hero_pct",
              "blink_bolt_pct"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.basic_attacks_per_second", out["epa_per_second"], d["basic_attacks_per_second"])
    chk("derived.attack_bucket_mult", out["attack_bucket_mult"], d["attack_bucket_mult"])
    chk("derived.bolt_surplus_trigger_rate", out["bolt_surplus_trigger_rate"], d["bolt_surplus_trigger_rate"])
    chk("derived.snipe_attack_rate", out["snipe_hit_rate"], d["snipe_attack_rate"])
    chk("derived.epa_attack_rate", out["epa_hit_rate"], d["epa_attack_rate"])
    GH.check_stunned_shares(chk, out, d)
    GH.check_engine_and_companion(chk, out, res)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(marksman, GOLDEN, compare, rtol, verbose)


def test_marksman_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
