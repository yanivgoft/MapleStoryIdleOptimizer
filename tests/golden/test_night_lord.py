#!/usr/bin/env python3
"""Golden test: ``engine.classes.night_lord.compute`` against the frozen numbers of the ORIGINAL Night Lord verify script
(tests/golden/night_lord_golden.json, regenerated by make_golden_night_lord.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_night_lord.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_night_lord.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import night_lord  # noqa: E402
import golden_harness as GH  # noqa: E402

FACTOR_MODE = GH.FACTOR_MODE        # legacy 300-clamp (workbook golden)

GOLDEN = HERE / "night_lord_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("showdown_dps", out["showdown_dps"], rows["SHOWDOWN"]["dps"])
    for k, v in out["skill_dps"].items():
        if k in rows:
            chk(f"skill_dps[{k}]", v, rows[k]["dps"])
        else:                                          # Shadow Partner / Night Lord's Mark / buffs / passives: no DPS of their own, only multipliers
            chk(f"skill_dps[{k}] == 0", v, 0.0)
    for k, pair in out["branch_pairs"].items():       # every Night Lord row has an explicit per-branch pair = the row's boss / normal DPS
        chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    chk("rows subset of skill_dps keys", sorted(set(rows) - set(out["skill_dps"])), [])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active", "avg_buff_mult",
              "as_bonus", "crit_damage_bonus", "crit_rate_bonus", "monster_dmg_bonus", "shadow_partner_mult"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.basic_attacks_per_second", out["showdown_per_second"], d["basic_attacks_per_second"])
    chk("derived.dark_sight_attack_avg", out["dark_sight_atk_avg"], d["dark_sight_attack_avg"])
    chk("derived.dark_sight_crit_rate_avg", out["dark_sight_crit_avg"], d["dark_sight_crit_rate_avg"])
    chk("derived.frailty_curse_self_fd_avg", out["frailty_self_avg"], d["frailty_curse_self_fd_avg"])
    chk("derived.alchemic_adrenaline_uptime", out["adrenalin_uptime"], d["alchemic_adrenaline_uptime"])
    chk("derived.alchemic_adrenaline_fd_avg", out["adrenalin_fd_avg"], d["alchemic_adrenaline_fd_avg"])
    chk("derived.alchemic_adrenaline_as_avg", out["adrenalin_as_avg"], d["alchemic_adrenaline_as_avg"])
    chk("derived.nimble_feet_avg", out["nimble_feet_avg"], d["nimble_feet_avg"])
    chk("derived.actions_per_second_pre_adrenalin", out["aps_pre_adrenalin"], d["actions_per_second_pre_adrenalin"])
    chk("derived.toxic_venom_trigger_rate", out.get("total_hit_rate", 0.0), d["toxic_venom_trigger_rate"])    # (the script leaves it undefined while Toxic Venom is locked)
    chk("derived.artifact_attack_pct", 0, d["artifact_attack_pct"])                                           # the hook is off in every golden case
    chk("derived.attack_rates keys", sorted(out["hit_rate"]), sorted(d["attack_rates"]))
    for k, v in out["hit_rate"].items():
        chk(f"derived.attack_rates[{k}]", v, d["attack_rates"][k])
    GH.check_stunned_shares(chk, out, d)
    GH.check_engine_and_companion(chk, out, res, casts_keys=True)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(night_lord, GOLDEN, compare, rtol, verbose)


def check_artifact_hook():
    """The artifact Attack% hook (the verify script ignores artifacts, so the golden runs it at 0): off == absent; on = ONE additive bucket with Dark
    Sight's Attack% (engine off: ``(1 + (DarkSight + Art)/100)(1 + Frailty)(1 + Adrenalin)``), and it feeds the timeline strip's A0 with the engine on."""
    problems = []
    base = night_lord.defaults("Chapter Hunt")
    base.update(level=140, flat_attack=1_209_199, attack_pct=34372.5, flat_luk=67948, luk_pct=344.2, dex=896)
    r0, r_off = night_lord.compute(base), night_lord.compute(dict(base, artifact_attack_pct=0))
    if r0["total_dps"] != r_off["total_dps"]:
        problems.append("hook 0 differs from absent")
    r20 = night_lord.compute(dict(base, artifact_attack_pct=20.0))
    d = r20["derived"]
    want = (1 + (d["dark_sight_attack_avg"] + 20.0) / 100) * (1 + d["frailty_curse_self_fd_avg"] / 100) * (1 + d["alchemic_adrenaline_fd_avg"] / 100)
    if d["avg_buff_mult"] != want:
        problems.append(f"engine-off bucket: {d['avg_buff_mult']!r} vs {want!r}")
    if not r20["total_dps"] > r0["total_dps"]:
        problems.append("hook did not raise the DPS (engine off)")
    wb = night_lord.defaults("World Boss")
    wb.update(level=140, flat_attack=1_209_199, attack_pct=34372.5, flat_luk=67948, luk_pct=344.2, dex=896)
    a, b = night_lord.compute(wb), night_lord.compute(dict(wb, artifact_attack_pct=20.0))
    if not (a["engine_on"] and b["engine_on"] and b["total_dps"] > a["total_dps"] and b["derived"]["avg_buff_mult"] > a["derived"]["avg_buff_mult"]):
        problems.append("hook did not raise the engine-on bucket / DPS")
    return problems


def test_artifact_hook():
    assert not check_artifact_hook()


def test_night_lord_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run, hook_check=check_artifact_hook)
