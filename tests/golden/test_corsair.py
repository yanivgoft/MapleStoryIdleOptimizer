#!/usr/bin/env python3
"""Golden test: ``engine.classes.corsair.compute`` against the frozen numbers of the ORIGINAL Corsair verify script
(tests/golden/corsair_golden.json, regenerated by make_golden_corsair.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_corsair.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_corsair.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import corsair  # noqa: E402
import golden_harness as GH  # noqa: E402

GOLDEN = HERE / "corsair_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("eight_legs_easton_dps", out["eight_legs_easton_dps"], rows["EIGHT_LEGS_EASTON"]["dps"])
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    for k, pair in out["branch_pairs"].items():       # every Corsair row has an explicit per-branch pair = the row's boss / normal DPS (locked rows have none)
        chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active",
              "crit_damage_bonus", "crit_rate_bonus", "final_damage_extra", "final_damage_rest", "monster_dmg_bonus", "maple_hero_pct",
              "ahoy_mateys_pct", "ahoy_mateys_proc_fd", "jolly_roger_full", "jolly_roger_pct", "roll_of_dice_pct", "crew_window"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.as_bonus", out["_nimble_feet_as_bonus"], d["as_bonus"])
    chk("derived.basic_attacks_per_second", out["eight_legs_easton_per_second"], d["basic_attacks_per_second"])
    chk("derived.attack_bucket_mult", out["attack_bucket_mult"], d["attack_bucket_mult"])
    chk("derived.quickdraw_factor", out["qd_factor"], d["quickdraw_factor"])
    chk("derived.quickdraw_damage_mult", out["qd_damage_mult"], d["quickdraw_damage_mult"])
    GH.check_stunned_shares(chk, out, d)
    GH.check_engine_and_companion(chk, out, res)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(corsair, GOLDEN, compare, rtol, verbose)


def test_corsair_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
