#!/usr/bin/env python3
"""Regenerates (or, with --check, verifies) engine/data/artifacts.py from the artifact data tables of src/build_fp_mage_workbook.py
(byte-identical across the 12 builders).  The builder is parsed with ``ast`` and only its plain-data assignments are executed - it is
never imported (it pulls in openpyxl and builds a workbook at import time).

    python3 tests/golden/gen_artifact_data.py            # rewrite engine/data/artifacts.py
    python3 tests/golden/gen_artifact_data.py --check    # exit 1 when the engine copy differs from the builder
"""
import ast
import pprint
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BUILDER = REPO / "src" / "build_fp_mage_workbook.py"
OUT = REPO / "engine" / "data" / "artifacts.py"

# names assigned at module level in the builder, in the order they are written to the engine copy
NAMES = ["ARTIFACT_LABELS", "ARTIFACT_RANK", "ARTIFACT_RANK_DEFAULT_STAR", "GROWTH_DUNGEON_CONTENT_TYPES", "ARTIFACT_STAR_VALUES", "ARTIFACT_NO_DPS_EFFECT",
         "CHALICE_PROC_CHANCE", "CHALICE_KILLS_PER_MINUTE",
         "ARTIFACT_POTENTIAL_RARITIES", "ARTIFACT_POTENTIAL_VALUES", "ARTIFACT_POTENTIAL_STAT_TO_SWEEP_KEY"]
# statements needed to build ARTIFACT_RANK (an update() / dict-comprehension sequence)
RANK_STMTS = ("ARTIFACT_RANK",)

HEADER = '''"""Artifact data tables of the FP-Mage workbook (``src/build_fp_mage_workbook.py``; the 12 builders carry byte-identical copies),
as plain Python data.  GENERATED by ``tests/golden/gen_artifact_data.py`` - do not edit by hand; ``--check`` verifies it against the builder.

ARTIFACT_LABELS      artifact id -> name shown in the Inputs slot dropdowns / ArtifactsInput sheet
ARTIFACT_RANK        artifact id -> 'Epic' | 'Unique' | 'Legendary' (drives the default star level and the potential-line count)
ARTIFACT_STAR_VALUES value arrays by star 0..5 (star index is 0-based: 5 is the maximum tier; 'Not Unlocked' reads as star 0 in the workbook)
                     ('arwens_glass_shoes_summon_time_increase_pct': star 0 = 20, star 5 = 40 and the linear steps 24/28/32/36
                     in between are all user-confirmed (2026-11-19))
ARTIFACT_NO_DPS_EFFECT artifact id -> reason: artifacts that genuinely have no DPS effect in the model (stat not used / content not modelled)
ARTIFACT_POTENTIAL_*  Artifact Potential lines (reference-only calculator, not wired into DPS): rarities, value per (stat, rarity) and the
                     Sensitivity key each stat maps to (None = no DPS bucket)
"""
'''


def parse_builder():
    tree = ast.parse(BUILDER.read_text())
    ns = {}
    wanted = set(NAMES)
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            f = node.value.func                      # ARTIFACT_RANK.update(...)
            if isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name) and f.value.id in RANK_STMTS:
                targets = [f.value.id]
        if any(t in wanted for t in targets) or (isinstance(node, ast.Assign) and any(t == "ARTIFACT_LABELS" for t in targets)):
            exec(compile(ast.Module([node], []), str(BUILDER), "exec"), ns)
    return {n: ns[n] for n in NAMES}


FOOTER = '''
# ---- artifacts the game added after the frozen workbooks (engine-only, patch 2026-11-26): merged here, WORKBOOK_* keep the workbook subset ----
from .artifacts_extra import extend as _extend  # noqa: E402

_extend(globals())
'''


def render(data):
    parts = [HEADER]
    for name in NAMES:
        parts.append(f"{name} = {pprint.pformat(data[name], width=140, sort_dicts=False)}\n")
    return "\n".join(parts) + FOOTER


if __name__ == "__main__":
    text = render(parse_builder())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("engine/data/artifacts.py differs from the builder's artifact tables")
            sys.exit(1)
        print("OK: engine/data/artifacts.py == builder artifact tables")
    else:
        OUT.write_text(text)
        print("wrote", OUT)
