#!/usr/bin/env python3
"""Golden test: ``engine.classes.ilm.compute`` against the frozen numbers of the ORIGINAL Ice/Lightning Mage verify script
(tests/golden/ice_lightning_mage_golden.json, regenerated by make_golden_ice_lightning_mage.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_ice_lightning_mage.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_ice_lightning_mage.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import ice_lightning_mage as ilm  # noqa: E402
import golden_harness as GH  # noqa: E402

FACTOR_MODE = GH.FACTOR_MODE        # legacy 300-clamp (workbook golden)

GOLDEN = HERE / "ice_lightning_mage_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("chain_dps", out["chain_dps"], rows["CHAIN_LIGHTNING"]["dps"])
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    w = out["normal_weight"]
    for k, (bd, nd, explicit, bm_, nm_) in out["branch_pairs"].items():
        val = out["chain_dps"] if k == "CHAIN_LIGHTNING" else out["skill_dps"][k]
        if not explicit:            # multiplier-style row: boss DPS = DPS x b / ((1-w) b + w n), exactly as the script's companion block forms it
            den = (1 - w) * bm_ + w * nm_
            bd, nd = val * bm_ / den, val * nm_ / den
        chk(f"boss_dps[{k}]", bd, rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", nd, rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active", "attack_bucket_sum",
              "as_bonus", "monster_dmg_bonus", "damage_bonus"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.chain_lightning_hits", out["chain_lightning_hits"], d["chain_lightning_hits"])
    chk("derived.basic_attacks_per_second", out["chain_lightning_per_second"], d["basic_attacks_per_second"])
    chk("derived.avg_buff_mult", out["avg_buff_mult"], d["avg_buff_mult"])
    GH.check_stunned_shares(chk, out, d)
    GH.check_engine_and_companion(chk, out, res)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(ilm, GOLDEN, compare, rtol, verbose)


def test_ice_lightning_mage_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
