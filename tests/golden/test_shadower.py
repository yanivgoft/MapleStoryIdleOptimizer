#!/usr/bin/env python3
"""Golden test: ``engine.classes.shadower.compute`` against the frozen numbers of the ORIGINAL Shadower verify script
(tests/golden/shadower_golden.json, regenerated by make_golden_shadower.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_shadower.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_shadower.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import shadower  # noqa: E402
import golden_harness as GH  # noqa: E402

GOLDEN = HERE / "shadower_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("cruel_stab_dps", out["cruel_stab_dps"], rows["CRUEL_STAB"]["dps"])
    assert set(out["skill_dps"]) == set(rows), "result rows differ from the verify script's skill_dps keys"
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    for k, pair in out["branch_pairs"].items():       # every Shadower row has an explicit per-branch pair = the row's boss / normal DPS
        chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
        chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "monster_defense", "fight_duration", "monster_type",
              "normal_weight", "skill_coefficient_base", "buff_cast_startup_time", "fixed_duration_active", "as_bonus", "crit_damage_bonus",
              "crit_rate_bonus", "monster_dmg_bonus", "maple_hero_pct", "avg_buff_mult", "shadow_partner_mult", "steal_avg",
              "meso_mastery_avg", "dark_sight_atk_avg", "dark_sight_crit_avg", "into_darkness_avg", "smokescreen_avg",
              "murderous_intent_mult", "meso_stack_avg"):
        chk(f"derived.{k}", out[k], d[k])
    chk("derived.basic_attacks_per_second", out["cruel_stab_per_second"], d["basic_attacks_per_second"])
    chk("derived.blood_money_stack_avg", out["bm_stack_avg"], d["blood_money_stack_avg"])
    chk("derived.attack_bucket_avg", out["dark_sight_atk_avg"] + out["steal_avg"] + out["meso_mastery_avg"], d["attack_bucket_avg"])
    chk("derived.toxic_venom_trigger_rate", out.get("total_hit_rate", 0.0), d["toxic_venom_trigger_rate"])
    GH.check_stunned_shares(chk, out, d)
    chk("derived.artifact_monster_dmg_bonus", 0, d["artifact_monster_dmg_bonus"])
    assert set(out["hit_rate"]) == set(d["attack_rates"])
    for k, v in out["hit_rate"].items():                # every row's attacks/s x target-count blend (Toxic Venom's trigger inputs)
        chk(f"derived.attack_rates[{k}]", v, d["attack_rates"][k])
    GH.check_engine_and_companion(chk, out, res)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(shadower, GOLDEN, compare, rtol, verbose)


def test_shadower_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
