#!/usr/bin/env python3
"""Golden test: ``engine.classes.fp_mage.compute`` against the frozen numbers of the ORIGINAL verify script
(tests/golden/fp_mage_golden.json, regenerated by make_golden.py).  Plain ``python3`` runnable, also collected by pytest.

    python3 tests/golden/test_fp_mage.py            # exact == (bit-exact); exits 1 on any difference
    python3 tests/golden/test_fp_mage.py --rtol 1e-12
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE))
from engine.classes import fp_mage  # noqa: E402
import golden_harness as GH  # noqa: E402

GOLDEN = HERE / "fp_mage_golden.json"


def compare(gold, res, rtol=0.0):
    """List of (field, golden, engine) differences for one case."""
    out, diffs, chk, done = GH.begin(gold, res, rtol, reference_error=False)
    if done:
        return diffs
    rows = {r["key"]: r for r in res["skills"]}
    chk("basic_dps", out["basic_dps"], rows["BASIC_ATTACK"]["dps"])
    for k, v in out["skill_dps"].items():
        chk(f"skill_dps[{k}]", v, rows[k]["dps"])
    for k, pair in out["branch_pairs"].items():
        if pair[2]:                                   # explicit per-branch units: the pair IS the row's boss / normal DPS
            chk(f"boss_dps[{k}]", pair[0], rows[k]["boss_dps"])
            chk(f"normal_dps[{k}]", pair[1], rows[k]["normal_dps"])
    d = res["derived"]
    for k in ("attack", "stat_damage", "actions_per_second", "cast_rate", "basic_attacks_per_second", "avg_buff_mult", "as_bonus",
              "burning_magic_mult", "elemental_decrease_mult", "monster_defense", "fight_duration", "monster_type", "normal_weight",
              "skill_coefficient_base", "buff_cast_startup_time", "element_amp_pct", "arcane_aim_pct", "fervent_drain_pct",
              "buff_mastery_pct", "fixed_duration_active", "attack_bucket_sum"):
        chk(f"derived.{k}", out[k], d[k])
    GH.check_stunned_shares(chk, out, d)
    for k in ("meteor_x", "meteor_proc_rate", "ignite_ticks_per_s", "flame_haze_dot_stack_multiplier", "flame_haze_total_stacks"):
        mine = d[{"meteor_x": "meteor_attempts_per_s"}.get(k, k)]
        for br, v in out[k].items():
            chk(f"derived.{k}[{br}]", v, mine[br])
    GH.check_engine_and_companion(chk, out, res)
    return diffs


def run(rtol=0.0, verbose=True):
    return GH.run_golden(fp_mage, GOLDEN, compare, rtol, verbose)


def test_fp_mage_matches_golden():
    n, bad = run(0.0)
    assert n > 0 and not bad, f"{len(bad)} of {n} golden cases differ"


if __name__ == "__main__":
    GH.main(run)
